package com.sudoplatform.sudoprivacyinteraction.internal.domain.entities.action

/**
 * Input for [ActionService.initiate].
 *
 * @property dataHolderId [String] The data holder relationship to scope the action to.
 * @property intent [ActionIntentEntity] The intent of the action to initiate.
 * @property fulfilmentMethod [ActionFulfilmentMethodEntity] The fulfilment method the client was
 *  offered for this intent.
 */
internal data class InitiateActionInput(
    val dataHolderId: String,
    val intent: ActionIntentEntity,
    val fulfilmentMethod: ActionFulfilmentMethodEntity,
)

/**
 * Input for [ActionService.listAvailable].
 *
 * @property dataHolderId [String] The data holder relationship to list available actions for.
 */
internal data class ListAvailableActionsInput(
    val dataHolderId: String,
)

/**
 * Output for [ActionService.listAvailable].
 *
 * @property items [List] The available actions retrieved in this query.
 * @property nextToken [String] A token generated by a previous call to allow for pagination.
 */
internal data class ListAvailableActionsOutput(
    val items: List<AvailableActionEntity>,
    val nextToken: String? = null,
)

/**
 * Core entity representation of an action service used in business logic.
 */
internal interface ActionService {
    /**
     * Initiate an action against a data holder relationship.
     *
     * @param input [InitiateActionInput] Parameters used to initiate the action.
     * @return The initiated [ActionEntity].
     */
    suspend fun initiate(input: InitiateActionInput): ActionEntity

    /**
     * Confirm that an assisted or delegated action was completed.
     *
     * @param id [String] The unique identifier of the action to confirm.
     * @return The updated [ActionEntity].
     */
    suspend fun confirmOutcome(id: String): ActionEntity

    /**
     * List the actions currently available for a data holder relationship.
     *
     * @param input [ListAvailableActionsInput] Parameters used to list available actions.
     * @return A [ListAvailableActionsOutput] of available actions.
     */
    suspend fun listAvailable(input: ListAvailableActionsInput): ListAvailableActionsOutput
}
