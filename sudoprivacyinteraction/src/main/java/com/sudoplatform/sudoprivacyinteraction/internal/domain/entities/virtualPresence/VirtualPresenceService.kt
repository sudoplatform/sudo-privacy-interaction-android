package com.sudoplatform.sudoprivacyinteraction.internal.domain.entities.virtualPresence

import com.sudoplatform.sudoprivacyinteraction.internal.domain.entities.RelationshipProviderEntity
import com.sudoplatform.sudoprivacyinteraction.internal.domain.entities.VirtualPresenceEntity
import com.sudoplatform.sudoprivacyinteraction.internal.domain.entities.inputs.ScanOptionsEntity

/**
 * Auth code input for connecting a virtual presence.
 *
 * @property authCode [String] The auth code value.
 * @property redirectUri [String] The optional redirect URI value.
 */
internal data class AuthCodeInput(
    val authCode: String,
    val redirectUri: String? = null,
)

/**
 * Refresh token credential input for connecting a virtual presence.
 *
 * @property refreshToken [String] The refresh token value.
 * @property providerIdentity [String] The identity associated with the provider.
 * @property scopes [List] Optional OAuth scopes associated with the token.
 * @property expiresInEpochMs [Double] Optional expiration time in milliseconds since epoch.
 */
internal data class RefreshTokenInput(
    val refreshToken: String,
    val providerIdentity: String,
    val scopes: List<String>? = null,
    val expiresInEpochMs: Double? = null,
)

/**
 * Input for [VirtualPresenceService.connect].
 *
 * @property authCode [AuthCodeInput] An authorization code obtained from the OAuth flow.
 * @property refreshToken [RefreshTokenInput] A pre-obtained refresh token credential.
 * @property relationshipProvider [RelationshipProviderEntity] The relationship provider to
 *  associate with the connection.
 */
internal data class ConnectVirtualPresenceInput(
    val authCode: AuthCodeInput? = null,
    val refreshToken: RefreshTokenInput? = null,
    val relationshipProvider: RelationshipProviderEntity? = null,
)

/**
 * Input for [VirtualPresenceService.list].
 *
 * @property limit [Int] Number of records to return.
 * @property nextToken [String] A token generated by a previous call to allow for pagination.
 */
internal data class ListVirtualPresencesInput(
    val limit: Int? = null,
    val nextToken: String? = null,
)

/**
 * Input for [VirtualPresenceService.rescan].
 *
 * @property id [String] The unique identifier of the virtual presence to rescan.
 * @property options [ScanOptionsEntity] Optional scan options to control the rescan behavior.
 */
internal data class RescanVirtualPresenceInput(
    val id: String,
    val options: ScanOptionsEntity? = null,
)

/**
 * Output for [VirtualPresenceService.list].
 *
 * @property items [List] The list of virtual presences retrieved in this query.
 * @property nextToken [String] A token generated by a previous call to allow for pagination.
 */
internal data class ListVirtualPresencesOutput(
    val items: List<VirtualPresenceEntity>,
    val nextToken: String? = null,
)

/**
 * Core entity representation of a virtual presence service used in business logic.
 * Used to perform operations for virtual presences.
 */
internal interface VirtualPresenceService {
    /**
     * Connect a virtual presence using an auth code or refresh token.
     *
     * @param input [ConnectVirtualPresenceInput] Parameters used to connect a virtual presence.
     * @return The connected [VirtualPresenceEntity].
     */
    suspend fun connect(input: ConnectVirtualPresenceInput): VirtualPresenceEntity

    /**
     * Disconnect a virtual presence by ID.
     *
     * @param id [String] The unique identifier of the virtual presence to disconnect.
     * @return The disconnected [VirtualPresenceEntity].
     */
    suspend fun disconnect(id: String): VirtualPresenceEntity

    /**
     * Retrieve a list of virtual presences.
     *
     * @param input [ListVirtualPresencesInput] Parameters used to list virtual presences.
     * @return A [ListVirtualPresencesOutput] of virtual presences matching the search criteria.
     */
    suspend fun list(input: ListVirtualPresencesInput): ListVirtualPresencesOutput

    /**
     * Rescan a virtual presence by ID.
     *
     * @param input [RescanVirtualPresenceInput] Parameters used to rescan a virtual presence.
     * @return The rescanned [VirtualPresenceEntity].
     */
    suspend fun rescan(input: RescanVirtualPresenceInput): VirtualPresenceEntity
}
